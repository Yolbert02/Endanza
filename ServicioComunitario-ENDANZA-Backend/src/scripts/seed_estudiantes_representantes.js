// Formatea fecha DD/MM/YYYY a YYYY-MM-DD
function parseDate(dateStr) {
  if (!dateStr || dateStr.includes("#") || dateStr.includes("VALOR")) return "2010-01-01";
  const parts = dateStr.trim().split("/");
  if (parts.length === 3) {
    const day = parts[0].padStart(2, "0");
    const month = parts[1].padStart(2, "0");
    const year = parts[2];
    if (isNaN(parseInt(year))) return "2010-01-01";
    return `${year}-${month}-${day}`;
  }
  return "2010-01-01";
}

// Normaliza el nombre de nivel de danza para mapear con Nivel_Danza
function normalizeDanceLevel(especialidad, grado) {
  const esp = (especialidad || "").toUpperCase().trim();
  const grd = (grado || "").toUpperCase().trim();

  if (grd.includes("PRE BALLET") || grd.includes("PREBALLET")) {
    return "Pre-Ballet";
  }
  if (grd.includes("PREPA") || grd.includes("PREPARATORIO")) {
    return "Preparatorio";
  }

  // Años 1 al 4 (Componente General)
  if (grd.startsWith("1")) return "1er Año";
  if (grd.startsWith("2")) return "2do Año";
  if (grd.startsWith("3")) return "3er Año";
  if (grd.startsWith("4")) return "4to Año";

  // Años 5 al 8 (Componente Especializado)
  let prefix = "";
  if (grd.startsWith("5")) prefix = "5to Año";
  else if (grd.startsWith("6")) prefix = "6to Año";
  else if (grd.startsWith("7")) prefix = "7mo Año";
  else if (grd.startsWith("8")) prefix = "8vo Año";
  else prefix = `${grd} Año`;

  if (esp.includes("CLASICA") || esp.includes("CLÁSICA")) {
    return `${prefix} - Danza Clásica`;
  }
  if (esp.includes("TRADICIONAL")) {
    return `${prefix} - Danza Tradicional`;
  }
  if (esp.includes("CONTEMPORANEA") || esp.includes("CONTEMPORÁNEA")) {
    return `${prefix} - Danza Contemporánea`;
  }

  return prefix;
}

